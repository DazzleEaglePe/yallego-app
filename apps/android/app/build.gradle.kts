// Gradle no carga `local.properties` como propiedades del proyecto por sí solo
// (a diferencia de `gradle.properties`); solo AGP lee de ahí, y únicamente
// `sdk.dir`. docs/11_ESTRUCTURA_PROYECTO.md §11.3 pide `API_BASE_URL_DEBUG` y
// `API_BASE_URL_RELEASE` ahí para no versionar IPs de desarrollo.
val localProperties = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) file.inputStream().use(::load)
}

fun localProperty(key: String, default: String): String =
    (localProperties.getProperty(key) ?: System.getenv(key))?.takeIf { it.isNotBlank() } ?: default

